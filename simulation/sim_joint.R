## =====================================================================
##  Simulate a joint amyloid-tau cohort from the joint model, on the REAL
##  design (every subject's amyloid and tau scan ages, covariates and
##  missingness exactly as observed), with population parameters you
##  choose -- typically the posterior means of a fit, with one changed.
##
##      source("run_joint_model.R"); source("simulation/sim_joint.R")
##      truth <- joint_truth_from_fit(fit)           # posterior means
##      truth$beta <- 0                              # the change under test
##      sim   <- simulate_joint(dat, truth, bA, bT, vA, vT, seed = 1)
##      fit0  <- fit_joint_model("struct", dat = sim$dat, ...)
##
##  Paths are generated by the same clock rule as the compiled densities
##  (nfExposure / eq. (21) of the proposal), in plain R.
## =====================================================================

## population parameters from a fit: means over the second half of each chain
joint_truth_from_fit <- function(fit) {
  ch <- do.call(rbind, lapply(fit$chains, function(m) m[(nrow(m) %/% 2 + 1):nrow(m), ]))
  mu <- colMeans(ch)
  g <- function(nm, k) unname(mu[sprintf("%s[%d]", nm, k)])
  list(theta = sapply(1:fit$bA$K, g, nm = "theta"), theta_T = sapply(1:fit$bT$K, g, nm = "theta_T"),
       nu = sapply(1:fit$vA$K, g, nm = "nu"), nu_T = sapply(1:fit$vT$K, g, nm = "nu_T"),
       mu_b = mu[["mu_b"]], mu_b_T = mu[["mu_b_T"]], sigma_b = mu[["sigma_b"]], sigma_b_T = mu[["sigma_b_T"]],
       gamma = sapply(1:3, g, nm = "gamma"), gamma_T = sapply(1:3, g, nm = "gamma_T"),
       sigma_alpha = mu[["sigma_alpha"]], sigma_alpha_T = mu[["sigma_alpha_T"]],
       psi = sapply(1:2, g, nm = "psi"), psi_T = sapply(1:2, g, nm = "psi_T"),
       sigma_delta = mu[["sigma_delta"]], sigma_delta_T = mu[["sigma_delta_T"]],
       phi = sapply(1:3, g, nm = "phi"), phi_T = sapply(1:3, g, nm = "phi_T"),
       beta = mu[["beta"]], rho_alpha = mu[["rho_alpha"]])
}

simulate_joint <- function(dat, truth, bA, bT, vA, vT, seed = 1L,
                           SA = SETTINGS, ST = SETTINGS_TAU, SJ = SETTINGS_JOINT) {
  set.seed(seed)
  n <- dat$n_subj; Xg <- cbind(1, dat$X)
  rA <- rate_grid(bA, truth$theta);   GA <- clock_grid(bA, rA, SA$thresh, SA$r_min)
  rT <- rate_grid(bT, truth$theta_T); GT <- clock_grid(bT, rT, ST$thresh, ST$r_min)
  mfun <- function(y) exp(truth$beta * (plogis((y - SA$thresh) / SJ$d_coup) - 0.5))
  EA <- sa_cumtrapz(mfun(bA$y) / pmax(rA, SA$r_min), bA$step)
  omA <- as.numeric(exp(vA$B %*% truth$nu)); omT <- as.numeric(exp(vT$B %*% truth$nu_T))
  amin <- SA$alpha_min; amax <- SA$alpha_max

  ## ---- latent classes and histories ----------------------------------
  pi_i <- plogis(Xg %*% truth$phi); q_i <- plogis(Xg %*% truth$phi_T)
  ZA <- rbinom(n, 1, pi_i); ZT <- ZA * rbinom(n, 1, q_i)
  rho <- truth$rho_alpha
  VA <- rnorm(n); VT <- rho * VA + sqrt(1 - rho^2) * rnorm(n)
  tweib_inv <- function(u, xg, sa) {
    lam <- exp(xg); kap <- 1 / sa
    C <- 1 - exp(-((amax - amin) / lam)^kap)
    amin + lam * (-log(1 - u * C))^(1 / kap)
  }
  alphaA <- tweib_inv(pnorm(VA), Xg %*% truth$gamma,   truth$sigma_alpha)
  alphaT <- tweib_inv(pnorm(VT), Xg %*% truth$gamma_T, truth$sigma_alpha_T)
  rtn <- function(n) { z <- rnorm(n); while (any(abs(z) > SA$z_bound)) { k <- abs(z) > SA$z_bound; z[k] <- rnorm(sum(k)) }; z }
  zA <- rtn(n); zT <- rtn(n)
  deltaA <- as.numeric(dat$X %*% truth$psi   + truth$sigma_delta   * zA)
  deltaT <- as.numeric(dat$X %*% truth$psi_T + truth$sigma_delta_T * zT)
  rtrunc_below <- function(n, m, s, hi) { b <- rnorm(n, m, s); while (any(b >= hi)) { k <- b >= hi; b[k] <- rnorm(sum(k), m, s) }; b }
  bA_i <- rtrunc_below(n, truth$mu_b,   truth$sigma_b,   SA$thresh)
  bT_i <- rtrunc_below(n, truth$mu_b_T, truth$sigma_b_T, ST$thresh)

  ## ---- paths -----------------------------------------------------------
  GbA <- sa_interp(bA$y, GA, truth$mu_b); EbA <- sa_interp(bA$y, EA, truth$mu_b)
  GbT <- sa_interp(bT$y, GT, truth$mu_b_T)
  off_grid <- 0L
  Apath <- function(i, a) {                  # candidate accumulator amyloid path
    g <- GbA + exp(deltaA[i]) * pmax(a - alphaA[i], 0)
    bad <- g > GA[bA$n]; if (any(bad)) { off_grid <<- off_grid + sum(bad); g[bad] <- GA[bA$n] }
    sa_inv_monotone(bA$y, GA, g)
  }
  Psi <- function(i, u) {                   # exposure since amyloid departure
    ifelse(u <= alphaA[i], mfun(truth$mu_b) * (u - alphaA[i]),
           exp(-deltaA[i]) * (sa_interp(bA$y, EA, Apath(i, u)) - EbA))
  }
  Tpath <- function(i, a) {
    g <- GbT + exp(deltaT[i]) * pmax(Psi(i, a) - Psi(i, alphaT[i]), 0)
    bad <- g > GT[bT$n]; if (any(bad)) { off_grid <<- off_grid + sum(bad); g[bad] <- GT[bT$n] }
    sa_inv_monotone(bT$y, GT, g)
  }
  y_mat <- dat$y_mat * 0; y_tau <- dat$y_tau_mat * 0
  for (i in seq_len(n)) {
    ja <- seq_len(dat$n_obs[i]); aa <- dat$age_mat[i, ja]
    MA <- if (ZA[i] == 1) Apath(i, aa) else rep(bA_i[i], length(ja))
    y_mat[i, ja] <- MA + sa_interp(vA$y, omA, MA) * rt(length(ja), SA$t_df)
    if (dat$n_obs_tau[i] > 0) {
      jt <- seq_len(dat$n_obs_tau[i]); at <- dat$age_tau_mat[i, jt]
      MT <- if (ZT[i] == 1) Tpath(i, at) else rep(bT_i[i], length(jt))
      y_tau[i, jt] <- MT + sa_interp(vT$y, omT, MT) * rt(length(jt), ST$t_df)
    }
  }
  ## keep observations inside the level grids (as the real data are)
  y_mat[y_mat != 0] <- pmin(pmax(y_mat[y_mat != 0], bA$lo + 0.01), bA$hi - 0.01)
  y_tau[y_tau != 0] <- pmin(pmax(y_tau[y_tau != 0], bT$lo + 0.01), bT$hi - 0.01)

  dat_sim <- dat
  dat_sim$y_mat <- y_mat; dat_sim$y_tau_mat <- y_tau
  dat_sim$x_init <- vapply(seq_len(n), function(i) mean(y_mat[i, seq_len(dat$n_obs[i])]), 0)
  xt <- vapply(seq_len(n), function(i) if (dat$n_obs_tau[i] > 0) mean(y_tau[i, seq_len(dat$n_obs_tau[i])]) else NA_real_, 0)
  xt[is.na(xt)] <- median(xt, na.rm = TRUE); dat_sim$x_init_tau <- xt

  list(dat = dat_sim, truth = truth, off_grid = off_grid,
       latent = data.frame(ZA = ZA, ZT = ZT, alphaA = alphaA, alphaT = alphaT,
                           deltaA = deltaA, deltaT = deltaT, bA = bA_i, bT = bT_i))
}
